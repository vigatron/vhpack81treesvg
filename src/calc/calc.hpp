#pragma once

#include "vhplatform.hpp"
#include "vhrect.hpp"
#include "tree.hpp"
#include "treearea.hpp"
#include "treegfx.hpp"
#include "layerarea.hpp"


class VHCalcHelper
{
    public:

        // -------------------------------------------------------------------------------------------------
        /// @brief Рассчитать геометрию рамки документа и итоговый размер SVG-документа
        /// @param width      Ширина области дерева (pxls)
        /// @param layscount  Количество слоёв (уровней глубины дерева)
        static void svgcalc_ramka      ( int width , int layscount );

        // -------------------------------------------------------------------------------------------------
        /// @brief Рекурсивно рассчитать координаты X/Y узлов дерева (от корня)
        /// @param rect       Прямоугольник области дерева
        /// @param tree       Дерево (вход)
        /// @param tgfx       Рассчитанная геометрия дерева (вход/выход - координаты)
        /// @param larea      Области слоёв (Y-координаты слоёв)
        /// @param layscount  Количество слоёв (уровней глубины дерева)
        static void CalcTreeGfx        ( const VHRect & rect, VHTree & tree , VHTreeGfx & tgfx , LayerArea & larea , int layscount );

    private:

        // -------------------------------------------------------------------------------------------------
        /// @brief Рассчитать ширину рамки с учетом минимальной ширины и отступов по бокам
        /// @param width  Ширина области дерева (pxls)
        /// @return Ширина рамки (pxls)
        static int  svgcalc_ramka_w    ( int width );

        // -------------------------------------------------------------------------------------------------
        /// @brief Рассчитать высоту рамки (шапки, деревья, тени, битовые поля, спектр)
        /// @param w          Ширина рамки (pxls)
        /// @param layscount  Количество слоёв (уровней глубины дерева)
        /// @return Высота рамки (pxls)
        static int  svgcalc_ramka_h    ( int w , int layscount );

        // -------------------------------------------------------------------------------------------------
        /// @brief Рассчитать геометрию одного дерева (header/caption/tree/shadows/bitfield/descript)
        /// @param tarea      Область дерева (выход - заполненные прямоугольники)
        /// @param r          Начальная Y-координата (pxls)
        /// @param w          Ширина области (pxls)
        /// @param layscount  Количество слоёв (уровней глубины дерева)
        /// @return Y-координата после последнего элемента блока (pxls)
        static int  svgcalc_treearea   ( TreeArea & tarea , int r , int w , int layscount );

        // -------------------------------------------------------------------------------------------------
        /// @brief Разрезать прямоугольник по горизонтали на две равные части
        /// @param r   Исходный прямоугольник
        /// @param r1  Левая половина (выход)
        /// @param r2  Правая половина (выход)
        /// @param dx  Дополнительное сужение половин относительно друг друга (pxls)
        static void splitrecth         ( const VHRect r, VHRect & r1, VHRect & r2 , int dx = 0 );

        // -------------------------------------------------------------------------------------------------
        /// @brief Разрезать прямоугольник по вертикали на две равные части
        /// @param r   Исходный прямоугольник
        /// @param r1  Верхняя половина (выход)
        /// @param r2  Нижняя половина (выход)
        /// @param dy  Дополнительное сужение половин относительно друг друга (pxls)
        static void splitrectv         ( const VHRect r, VHRect & r1, VHRect & r2 , int dy = 0 );
};
